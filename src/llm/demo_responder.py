"""Deterministic demo-mode answer built directly from retrieved text (NOT LLM generated).

It picks the sentences from the retrieved chunks that overlap most with the question."""
from __future__ import annotations

import re
from typing import Iterable, List

STOP = set("a an the is are do you i my me to of in on for and or can what how when where it be at with your have there".split())
DEMO_PREFIX = "**[Demo mode - extracted from the sample documents, not generated by an LLM]** "


def _words(s: str) -> set:
    return {w for w in re.findall(r"[a-z0-9']+", s.lower()) if w not in STOP}


def demo_answer(question: str, chunks: Iterable, max_sentences: int = 2) -> str:
    q = _words(question)
    scored: List[tuple] = []
    for c in chunks:
        for sent in re.split(r"(?<=[.!?])\s+|\n", c.text):
            sent = sent.strip()
            if len(sent) < 25 or sent.isupper():
                continue
            scored.append((len(q & _words(sent)), sent))
    scored.sort(key=lambda x: -x[0])
    best = [s for sc, s in scored[:max_sentences] if sc > 0] or [s for _, s in scored[:1]]
    return DEMO_PREFIX + " ".join(best) if best else DEMO_PREFIX + "Relevant text was found but could not be summarised."
